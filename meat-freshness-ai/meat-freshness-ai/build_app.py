# 앱 만들기: app_template.html + engine.js + model/model_web.json + data/samples/samples.json → index.html (파일 1개)
import json, os
here = os.path.dirname(os.path.abspath(__file__))
rd = lambda p: open(os.path.join(here, p), encoding="utf-8").read()
html = rd("app_template.html")
html = html.replace("/*__ENGINE__*/", rd("engine.js"))
html = html.replace("/*__MODEL__*/", rd("model/model_web.json").strip())
html = html.replace("/*__SAMPLES__*/", json.dumps(json.load(open(os.path.join(here, "data/samples/samples.json"), encoding="utf-8")), ensure_ascii=False, separators=(",", ":")))
open(os.path.join(here, "index.html"), "w", encoding="utf-8").write(html)
print("index.html", round(len(html.encode()) / 1024), "KB")
